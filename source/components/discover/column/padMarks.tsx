/*
 * ── THE LAUNCHPAD MARKS ──────────────────────────────────────────────
 *
 * One mark per launchpad, in white.
 *
 * ── TWO FORMATS, BECAUSE THE LOGOS ARE TWO KINDS OF THING ────────────
 *
 * Most are shapes: a capsule, a hexagon, a sack, a halo. Those are
 * OUTLINED, drawn to the weight Axiom uses on its own row — their
 * pump.fun mark is two elements at roughly a 1.3 stroke on a 24 box.
 *
 * A mascot is not a shape, it is a set of filled regions, and the
 * outline of a filled region is a hole. Outlining Bonk turned its white
 * muzzle into an open mouth and its black nose into a tongue sitting in
 * that mouth, six times over. Those are traced and FILLED instead.
 *
 * ── THE BUDGET IS THE POINT ──────────────────────────────────────────
 *
 * These render at about 17.5px. Two earlier sets were drawn at a 2
 * stroke with as many strokes as each mark seemed to want — PRINTR had
 * seven — and a mark with seven strokes at 17.5px is not a small mark,
 * it is a grey rectangle. One to three elements, and anything that did
 * not fit is gone rather than shrunk.
 */

const BASE = {
  fill: 'none',
  stroke: 'currentColor',
  strokeWidth: 1.35,
  strokeLinecap: 'round',
  strokeLinejoin: 'round',
} as const;

/* Outlined: for the marks that are shapes. */
function Mark({ children }: { children: React.ReactNode }) {
  return (
    <svg viewBox="0 0 24 24" width="100%" height="100%" {...BASE}>
      {children}
    </svg>
  );
}

/*
 * Filled: for the mascots.
 *
 * `evenodd` is what lets the inner contours cut holes — the eyes, the
 * nose, the muzzle's edge — instead of painting over the solid.
 */
function Glyph({ children }: { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width="100%"
      height="100%"
      fill="currentColor"
      fillRule="evenodd"
      stroke="none"
    >
      {children}
    </svg>
  );
}

