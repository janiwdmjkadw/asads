/*
 * The feed names a pad in a few shapes — a key, a label, a domain — so
 * the lookup is loose and returns UNDEFINED when nothing matches rather
 * than guessing. An unknown pad draws a neutral ring and no badge, which
 * is honest; picking the nearest name would put the wrong logo on a
 * token.
 */
export function findPad(name?: string | null): Pad | undefined {
  if (!name) return undefined;
  const k = name.toLowerCase().replace(/[^a-z]/g, '');
  return PADS[k] ?? Object.values(PADS).find((p) => k.includes(p.key));
}
